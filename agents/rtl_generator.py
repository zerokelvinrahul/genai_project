import os
import re
from pathlib import Path
from pydantic import BaseModel, Field
from langchain_core.messages import SystemMessage, HumanMessage

import config
from agents.base_agent import BaseLLMAgent
from utils.parsing import (
    RTLGenerationOutput,
    extract_verilog_code,
    extract_module_name,
    validate_verilog_syntax_basic
)
from utils.file_manager import FileManager

class RTLGenerator(BaseLLMAgent):
    def __init__(self, api_key: str | None = None, model_name: str | None = None):
        super().__init__(api_key=api_key, model_name=model_name, temperature=0.1)

    def generate(
        self,
        specification: str,
        module_name: str = "alu_16bit",
        save_filename: str = "alu_16bit_generated.v"
    ) -> tuple[RTLGenerationOutput, Path]:
        """
        Generates synthesizable Verilog RTL from natural language hardware specification.
        Uses structured output via LangChain with Pydantic schema validation.
        """
        prompt_template = (config.PROMPTS_DIR / "rtl_generation.txt").read_text(encoding="utf-8")
        prompt = (
            prompt_template
            .replace("{specification}", specification)
            .replace("{module_name}", module_name)
        )

        llm = self._get_llm()
        
        # Request structured output using Pydantic model
        messages = [
            SystemMessage(content="You are a hardware design engineer generating synthesizable Verilog RTL."),
            HumanMessage(content=prompt)
        ]
        try:
            structured_llm = llm.with_structured_output(RTLGenerationOutput)
            result: RTLGenerationOutput = self.invoke_with_retry(messages)
            if not isinstance(result, RTLGenerationOutput):
                raw_code = extract_verilog_code(result.content)
                result = RTLGenerationOutput(
                    module_name=module_name,
                    verilog_code=raw_code,
                    explanation="Generated RTL module",
                    supported_operations=[],
                    interface_description=""
                )
        except Exception as e:
            # Fallback to direct prompt and manual parsing if structured output fails
            raw_resp = self.invoke_with_retry(messages)
            extracted_code = extract_verilog_code(raw_resp.content)
            result = RTLGenerationOutput(
                module_name=module_name,
                verilog_code=extracted_code,
                explanation="Generated via direct text prompt fallback.",
                supported_operations=["000-111 ALU operations"],
                interface_description=f"Standard {module_name} interface"
            )

        # Clean extracted verilog code in case wrapped in fences
        clean_code = extract_verilog_code(result.verilog_code)
        result.verilog_code = clean_code

        # Validate basic syntax & module structure
        is_valid, msg = validate_verilog_syntax_basic(clean_code)
        if not is_valid:
            raise ValueError(f"Malformed RTL generated by LLM: {msg}")

        # Ensure module name matches
        detected_name = extract_module_name(clean_code)
        if detected_name and detected_name != module_name:
            # Correct the module header to match the expected interface name
            clean_code = re.sub(rf"\bmodule\s+{re.escape(detected_name)}\b", f"module {module_name}", clean_code, count=1)
            result.verilog_code = clean_code
            result.module_name = module_name

        # Save to disk
        out_path = FileManager.save_rtl(result.verilog_code, category="generated", filename=save_filename)
        return result, out_path

